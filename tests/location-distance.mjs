import assert from 'node:assert/strict';
import {canReuseLocation} from '../web/location.js';
const saved={regionKey:'CN/test',lat:0,lon:0};
assert(canReuseLocation(saved,0,0));
assert(canReuseLocation(saved,0,1.99/111.1949266));
assert(!canReuseLocation(saved,0,2.01/111.1949266));
assert(!canReuseLocation({...saved,regionKey:'coordinates:0,0'},0,0));
assert(!canReuseLocation(null,0,0));
assert(!canReuseLocation(saved,NaN,0));
assert(!canReuseLocation(saved,23,113));
assert(!canReuseLocation({...saved,lat:0,lon:2/111.1949266,anchorLat:0,anchorLon:0},0,2.5/111.1949266));
console.log('PASS: 2km boundary, no placeholder reuse, missing/invalid coordinate, distant city');
